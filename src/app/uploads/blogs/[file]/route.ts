import { promises as fs } from "fs";
import path from "path";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * Fallback for admin-uploaded blog images.
 *
 * `next start` / the standalone server snapshot `public/` at boot, so files written
 * by /api/admin/upload after startup would 404 until a restart. Files present at
 * boot are still served statically; anything newer falls through to this handler.
 */
const CONTENT_TYPES: Record<string, string> = {
  jpg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
  gif: "image/gif",
};

// Matches the names generated by /api/admin/upload — no separators, no traversal.
const SAFE_NAME = /^[A-Za-z0-9-]+\.(jpg|png|webp|gif)$/;

type RouteContext = {
  params: Promise<{ file: string }>;
};

export async function GET(_request: Request, context: RouteContext) {
  const { file } = await context.params;
  const match = SAFE_NAME.exec(file);
  if (!match) return new Response("Not found", { status: 404 });

  const filePath = path.join(process.cwd(), "public", "uploads", "blogs", file);
  try {
    const bytes = await fs.readFile(filePath);
    return new Response(new Uint8Array(bytes), {
      headers: {
        "Content-Type": CONTENT_TYPES[match[1]],
        "Cache-Control": "public, max-age=31536000, immutable",
        "X-Content-Type-Options": "nosniff",
      },
    });
  } catch {
    return new Response("Not found", { status: 404 });
  }
}
